export const LOCALES = ["de", "en", "fr", "es", "it", "pt-BR", "nl", "ja", "ko", "zh-Hans", "ru"] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = "de";

/** Each language in its own name, for the language picker and the legal pages. */
export const LOCALE_NAMES: Record<Locale, string> = {
  de: "Deutsch",
  en: "English",
  fr: "Français",
  es: "Español",
  it: "Italiano",
  "pt-BR": "Português (Brasil)",
  nl: "Nederlands",
  ja: "日本語",
  ko: "한국어",
  "zh-Hans": "简体中文",
  ru: "Русский",
};

/**
 * URL path segment of each language on the legal pages: lowercase, the same codes as on the developer's
 * other sites (pt-BR → pt-br, zh-Hans → zh). The locale itself stays the BCP 47 tag for lang/hreflang.
 */
export const LOCALE_URL_CODES: Record<Locale, string> = {
  de: "de",
  en: "en",
  fr: "fr",
  es: "es",
  it: "it",
  "pt-BR": "pt-br",
  nl: "nl",
  ja: "ja",
  ko: "ko",
  "zh-Hans": "zh",
  ru: "ru",
};

/** The language of a legal page URL segment (see LOCALE_URL_CODES). */
export function localeFromUrlCode(code: string): Locale | undefined {
  return LOCALES.find((locale) => LOCALE_URL_CODES[locale] === code);
}

/**
 * The supported language for a browser language tag, matched by its primary subtag: "pt-PT" → "pt-BR",
 * "zh-TW" → "zh-Hans", "en-GB" → "en". Shared with the redirect script of the legal pages.
 */
export function matchLocale(tag: string): Locale | undefined {
  const base = tag.toLowerCase().split(/[-_]/)[0];
  return LOCALES.find((code) => code.toLowerCase().split("-")[0] === base);
}

/** The first of the browser's preferred languages that Tandem supports, else German. */
export function detectLocale(preferred: readonly string[]): Locale {
  for (const tag of preferred) {
    const locale = matchLocale(tag);
    if (locale) return locale;
  }
  return DEFAULT_LOCALE;
}

